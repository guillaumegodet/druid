// Bundle of the PostgreSQL driver for the Cloudflare Pages Functions: functions/_generated/pg.js (ignored by git),
// written by `npm run build` right after scripts/prepare-cloudflare-assets.cjs (which empties functions/_generated/) on
// every build, Pages or not, and by the Functions tests when absent.
//
// Why: the Functions are compiled by the wrangler of the Pages build system, which rejects the bare Node built-ins
// required by node-postgres (`require('events')`, `net`, `tls`…) unless it receives the `nodejs_compat` flag — and the
// flag of the project settings is not handed to that compilation (seen on 2026-10-14: 24 "Could not resolve" errors with
// the flag set). The same wrangler accepts `node:*` imports without any flag (left external, resolved by the runtime).
// So the driver is bundled here first, with every built-in rewritten to `node:<name>`; the runtime still needs the
// Node.js compatibility of the project (`nodejs_compat`, default from compatibility date 2026-08-04).
const fs = require('fs');
const path = require('path');
const { builtinModules } = require('module');
const esbuild = require('esbuild');

const ROOT = path.join(__dirname, '..');
const FUNCTIONS_PG_BUNDLE = path.join(ROOT, 'functions', '_generated', 'pg.js');
const BUILTINS = new Set(builtinModules.filter((name) => !name.startsWith('_')));
const isBuiltin = (name) => BUILTINS.has(name) || BUILTINS.has(name.split('/')[0]);

const nodePrefixPlugin = {
  name: 'druid-node-prefix',
  setup(build) {
    // `events`, `node:events`, `util/types`… → `node:events`, `node:util/types`, reached through a small ES module
    // (namespace druid-node) so that the CommonJS `require()` of the driver becomes a static `import` of the bundle:
    // a bare external would leave a dynamic `require("node:events")`, refused by the Workers runtime in an ES module.
    build.onResolve({ filter: /^(node:)?[a-z_][a-z0-9_]*(\/[a-z_][a-z0-9_]*)?$/ }, (args) => {
      const name = args.path.replace(/^node:/, '');
      if (!isBuiltin(name)) return null;
      return args.namespace === 'druid-node' ? { path: `node:${name}`, external: true } : { path: `node:${name}`, namespace: 'druid-node' };
    });
    build.onLoad({ filter: /.*/, namespace: 'druid-node' }, (args) => ({
      loader: 'js',
      contents: `import * as m from '${args.path}';\nexport * from '${args.path}';\nexport default m.default ?? m;\n`,
    }));
    // pg-cloudflare opens the TCP socket through the runtime module.
    build.onResolve({ filter: /^cloudflare:/ }, (args) => ({ path: args.path, external: true }));
    // Optional native binding of node-postgres (libpq): never available on Cloudflare.
    build.onResolve({ filter: /^pg-native$/ }, () => ({ path: 'pg-native', namespace: 'druid-stub' }));
    build.onLoad({ filter: /.*/, namespace: 'druid-stub' }, () => ({
      loader: 'js',
      contents: 'module.exports = function PgNativeUnavailable() { throw new Error("pg-native is not available on Cloudflare"); };',
    }));
  },
};

/** Writes the bundle (atomically: a parallel test may build it too) and returns its path. */
const buildFunctionsPg = async ({ outfile = FUNCTIONS_PG_BUNDLE } = {}) => {
  const result = await esbuild.build({
    stdin: { contents: "import pg from 'pg';\nexport default pg;\n", resolveDir: ROOT, loader: 'js', sourcefile: 'functions-pg-entry.js' },
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'browser',
    conditions: ['workerd', 'worker', 'browser'],
    target: 'es2022',
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: '// Generated by scripts/functions_pg_bundle.cjs (node-postgres, Node built-ins as node:*) — do not edit.' },
    plugins: [nodePrefixPlugin],
  });
  const [output] = result.outputFiles;
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  const tmp = `${outfile}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, output.contents);
  fs.renameSync(tmp, outfile);
  return outfile;
};

module.exports = { buildFunctionsPg, FUNCTIONS_PG_BUNDLE };

if (require.main === module) {
  buildFunctionsPg().then((out) => console.log(`[functions-pg-bundle] ${path.relative(process.cwd(), out)} written`), (err) => {
    console.error(err);
    process.exit(1);
  });
}
