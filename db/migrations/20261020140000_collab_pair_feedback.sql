-- Opinions of the Druid users on the suggested connections between researchers (druid-internal
-- `docs/plan-binomes-chercheurs.md`, lot 4). One per user and pair, the last one wins. The pair is keyed by stable
-- author keys (`u:<Druid record id>`, or `n:<name>` when the directory join found nobody), sorted and joined by « | »:
-- the author ids of network.json change at each regeneration. The names and labs at the time of the opinion are kept
-- for the CSV export.
CREATE TABLE collab_pair_feedback (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pair_key   text NOT NULL,
  -- Structure of the dashboard the opinion was given from.
  slug       text NOT NULL,
  a_label    text NOT NULL,
  a_labs     text NOT NULL DEFAULT '',
  b_label    text NOT NULL,
  b_labs     text NOT NULL DEFAULT '',
  verdict    text NOT NULL CHECK (verdict IN ('relevant', 'already_in_contact', 'not_relevant')),
  comment    text NOT NULL DEFAULT '',
  author     text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (pair_key, author)
);
CREATE INDEX collab_pair_feedback_pair ON collab_pair_feedback (pair_key);

