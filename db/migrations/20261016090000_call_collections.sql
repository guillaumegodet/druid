-- Collection of the calls from their sources (druid-internal docs/plan-funding-calls.md, lot 2: Funding & Tenders
-- portal first). A collection run is logged; a programme remembers its last collection; the Horizon Europe programme
-- is now fed by the portal (its calls) and by the TRM reports (its matches).

CREATE TABLE call_collection (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source         text NOT NULL,
  programme_ids  text[] NOT NULL DEFAULT '{}',
  started_at     timestamptz NOT NULL DEFAULT now(),
  finished_at    timestamptz,
  status         text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'done', 'failed')),
  -- Calls of the active programmes seen in the listing, created, updated (text or dates changed), details fetched.
  calls_seen     integer NOT NULL DEFAULT 0,
  calls_new      integer NOT NULL DEFAULT 0,
  calls_updated  integer NOT NULL DEFAULT 0,
  details_fetched integer NOT NULL DEFAULT 0,
  error          text NOT NULL DEFAULT '',
  started_by     text NOT NULL DEFAULT ''
);
CREATE INDEX call_collection_started ON call_collection (started_at DESC);

