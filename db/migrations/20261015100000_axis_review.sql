-- Curation of the strategic axes in Druid (druid-internal docs/plan-axes-embeddings.md, lot 2): the decision of a user
-- on the automatic classification of one publication of a structure (biblio_etl/axes_embeddings.py, chosen_axe).
-- Replaces the Grist correction table of Centrale (lib/publications/axes.ts AXES_GRIST), imported at lot 5.
CREATE TABLE axis_review (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug            text NOT NULL,
  -- Publication key, stable across ETL runs: `doi:<lowercase doi>` when the publication has one, else
  -- `title:<normalised title>` (lib/publications/axisReviews.ts workKeyOf).
  work_key        text NOT NULL,
  doi             text NOT NULL DEFAULT '',
  title           text NOT NULL DEFAULT '',
  -- confirmed: the automatic axis is right; corrected: `axes` replaces it; rejected: the publication is outside the
  -- axes (unclassified on purpose); unsure: the reviewer could not decide (the automatic axis stays).
  decision        text NOT NULL CHECK (decision IN ('confirmed', 'corrected', 'rejected', 'unsure')),
  -- Retained axes, principal first; empty for rejected and unsure.
  axes            text[] NOT NULL DEFAULT '{}',
  -- What the automatic classification said when the decision was taken.
  auto_axis       text NOT NULL DEFAULT '',
  auto_confidence double precision,
  author          text NOT NULL DEFAULT '',
  note            text NOT NULL DEFAULT '',
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (slug, work_key)
);
CREATE INDEX axis_review_slug ON axis_review (slug);
CREATE TRIGGER axis_review_updated_at BEFORE UPDATE ON axis_review FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER axis_review_audit AFTER INSERT OR UPDATE OR DELETE ON axis_review FOR EACH ROW EXECUTE FUNCTION audit_row();

